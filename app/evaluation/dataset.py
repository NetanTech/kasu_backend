"""Labelled Nigerian-style records for measuring extraction accuracy (KASU-018).

Each case is one spreadsheet row as a trader might keep it (sales book, cashbook, or typed
ledger) and the values a careful bookkeeper would read from it. The rows are written to mirror
real informal records: naira written as ₦ / N / NGN / # / "naira", "k" and "m" shorthands,
day-first dates in many spellings, Excel serial dates, quantities with units and fractions,
and Nigerian descriptions (NEPA, keke, okada, POS charges, LGA levy, Mile 12, Alaba...).

They are constructed, not copied from merchant data. Replace or extend them with anonymised
real rows as pilot data comes in; the harness and thresholds stay the same.

Field names match the import column mapping: date, description, product, quantity, amount,
money_in, money_out, kind, category, customer, supplier.
Expected keys: occurred_on (ISO date), amount (string), quantity (string, optional),
kind, category (optional; only for expenses).
"""

from dataclasses import dataclass, field


