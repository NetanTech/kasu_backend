def insights_from(s: Snapshot) -> list[Insight]:
    found = [i for rule in RULES for i in rule(s)]
    return sorted(found, key=lambda i: SEVERITY_ORDER[i.severity])


# --------------------------------------------------------------------------- health score

HEALTH_WEIGHTS = {
    "revenue": 20,
    "profitability": 25,
    "cash_flow": 20,
    "expenses": 10,
    "customers": 10,
    "inventory": 10,
    "inflation_resilience": 5,
}


def _scale(value: Decimal, low: Decimal, high: Decimal) -> int:
    """Linear 0..100 between low (0 points) and high (100 points), clamped."""
    if high == low:
        return 100 if value >= high else 0
    score = (value - low) / (high - low) * 100
    return int(max(Decimal(0), min(Decimal(100), score)).quantize(Decimal(1)))


@dataclass
class Dimension:
    key: str
    weight: int
    score: int | None
    explanation: str

    def as_dict(self) -> dict:
        return asdict(self)


def health_from(s: Snapshot) -> dict:
    """PRD §17. Dimensions without enough data are skipped (not scored as zero), and the
    overall confidence reflects how much of the score is actually backed by data."""
    o = s.overview
    revenue = Decimal(o["revenue"]["value"])
    dims: list[Dimension] = []

    rev_chg = _d(o["change_vs_previous_pct"]["revenue"])
    dims.append(
        Dimension(
            "revenue",
            HEALTH_WEIGHTS["revenue"],
            _scale(rev_chg, Decimal(-20), Decimal(20)) if rev_chg is not None else None,
            f"Sales changed {rev_chg}% vs the previous period."
            if rev_chg is not None
            else "Need a previous period with sales to compare.",
        )
    )

    if revenue > 0:
        margin = pct(Decimal(o["net_profit"]["value"]), revenue)
        dims.append(
            Dimension(
                "profitability",
                HEALTH_WEIGHTS["profitability"],
                _scale(margin, Decimal(-10), Decimal(20)),
                f"Net profit margin is {margin}%"
                + (" (estimated)." if o["net_profit"]["basis"] == "estimated" else "."),
            )
        )
        cash_in = Decimal(o["cash_in"]["value"])
        flow = Decimal(o["net_cash_flow"]["value"])
        flow_pct = pct(flow, cash_in) if cash_in else Decimal(-100)
        recv_pct = pct(Decimal(o["receivables"]["value"]), revenue) or Decimal(0)
        cash_score = _scale(flow_pct, Decimal(-50), Decimal(20))
        cash_score = max(0, cash_score - int(max(Decimal(0), recv_pct - 30) / 2))
        dims.append(
            Dimension(
                "cash_flow",
                HEALTH_WEIGHTS["cash_flow"],
                cash_score,
                f"Net cash flow was {flow_pct}% of cash received; customers owe {recv_pct}% "
                "of period sales.",
            )
        )
        opex_ratio = pct(Decimal(o["operating_expenses"]["value"]), revenue)
        dims.append(
            Dimension(
                "expenses",
                HEALTH_WEIGHTS["expenses"],
                _scale(-opex_ratio, Decimal(-60), Decimal(-15)),
                f"Operating expenses are {opex_ratio}% of sales.",
            )
        )
    else:
        for key in ("profitability", "cash_flow", "expenses"):
            dims.append(Dimension(key, HEALTH_WEIGHTS[key], None, "No sales in this period."))

    c = s.customers
    if c["confidence"]["level"] != "low" and c["summary"]["active_customers"]:
        returning = _d(c["summary"]["returning_share_pct"]) or Decimal(0)
        top = _d(c["summary"]["top_customer_share_pct"]) or Decimal(0)
        score = int(returning / 2 + (100 - min(top, Decimal(100))) / 2)
        dims.append(
            Dimension(
                "customers",
                HEALTH_WEIGHTS["customers"],
                score,
                f"{returning}% of customers are returning; the top customer is {top}% of sales.",
            )
        )
    else:
        dims.append(
            Dimension(
                "customers",
                HEALTH_WEIGHTS["customers"],
                None,
                "Not enough sales with customer names.",
            )
        )

    inv = s.inventory
    tracked = [i for i in inv["_items"] if i.status != "unknown"]
    if tracked:
        dead_share = _d(inv["summary"]["dead_stock_share_pct"]) or Decimal(0)
        short = sum(1 for i in tracked if i.status in ("low", "out_of_stock"))
        short_share = Decimal(short) / len(tracked) * 100
        score = int(max(Decimal(0), 100 - dead_share / 2 - short_share / 2))
        dims.append(
            Dimension(
                "inventory",
                HEALTH_WEIGHTS["inventory"],
                score,
                f"{dead_share}% of stock value isn't selling; {short} of {len(tracked)} "
                "products are low or out of stock.",
            )
        )
    else:
        dims.append(
            Dimension(
                "inventory",
                HEALTH_WEIGHTS["inventory"],
                None,
                "Record product quantities to track stock.",
            )
        )

    dims.append(
        Dimension(
            "inflation_resilience",
            HEALTH_WEIGHTS["inflation_resilience"],
            None,
            "Inflation comparison isn't available yet.",
        )
    )

    scored = [d for d in dims if d.score is not None]
    covered = sum(d.weight for d in scored)
    score = round(sum(d.score * d.weight for d in scored) / covered) if covered else None
    level: Level = "high"
    reasons = []
    if covered < 85:
        level = "medium" if covered >= 50 else "low"
        missing = [d.key.replace("_", " ") for d in dims if d.score is None]
        reasons.append(f"Based on {covered}% of the full score; missing: {', '.join(missing)}.")
    if o["confidence"]["level"] != "high":
        if o["confidence"]["level"] == "low":
            level = "low"
        elif level == "high":
            level = "medium"
        reasons.append("Some of the underlying numbers are estimated or incomplete.")

    band = None
    if score is not None:
        band = "good" if score >= 70 else "fair" if score >= 40 else "needs_attention"
    return {
        "period": {"start": s.start, "end": s.end},
        "score": score,
        "band": band,
        "dimensions": [d.as_dict() for d in dims],
        "coverage_pct": covered,
        "confidence": {"level": level, "reasons": reasons},
        "note": "This score is a guide based on your recorded data, not a definitive "
        "judgement of your business.",
    }
