"""Deterministic business intelligence: alerts/recommendations and the Business Health Score.

Every insight follows the PRD §16 structure — what happened, why, evidence, what to consider,
potential impact — and carries a confidence level. All rules are plain arithmetic over the
ledger; nothing here is generated by a model, so every number can be traced and reproduced.
"""

import uuid
from collections import defaultdict
from dataclasses import asdict, dataclass, field
from datetime import date
from decimal import Decimal
from typing import Any, Literal

from sqlalchemy import func, select

from app.models import ImportRow
from app.models.enums import ImportRowStatus, Settlement, TransactionKind
from app.services.analytics import (
    LedgerView,
    Level,
    change,
    expense_breakdown_from,
    money,
    overview_from,
    pct,
    previous_period,
    product_performance_from,
)
from app.services.customers import customers_from
from app.services.inventory import inventory_from

K = TransactionKind
Severity = Literal["critical", "warning", "info", "positive"]
SEVERITY_ORDER = {"critical": 0, "warning": 1, "info": 2, "positive": 3}

# Thresholds (kept together so they're easy to tune with real merchant data).
REVENUE_DROP_PCT = Decimal(-10)
REVENUE_DROP_CRITICAL_PCT = Decimal(-25)
REVENUE_GROWTH_PCT = Decimal(15)
MARGIN_DROP_POINTS = Decimal(3)
INPUT_COST_RISE_PCT = Decimal(10)
EXPENSE_CATEGORY_RISE_PCT = Decimal(25)
EXPENSE_CATEGORY_MIN_SHARE_PCT = Decimal(10)
EXPENSES_OUTPACE_POINTS = Decimal(15)
RECEIVABLES_SHARE_PCT = Decimal(30)
CONCENTRATION_PCT = Decimal(40)


def naira(minor: Decimal | int) -> str:
    value = money(minor)
    return f"₦{value:,.0f}" if value == value.to_integral() else f"₦{value:,.2f}"


def _d(value: Any) -> Decimal | None:
    return None if value is None else Decimal(str(value))


