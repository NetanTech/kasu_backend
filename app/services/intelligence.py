@dataclass
class PriceChange:
    product_id: uuid.UUID
    name: str
    unit_cost_now: Decimal
    unit_cost_before: Decimal
    cost_change_pct: Decimal
    qty_bought_now: Decimal
    price_change_pct: Decimal | None  # selling price change, if the product sold in both


def _unit_prices(view: LedgerView, kind: K, start: date, end: date) -> dict[uuid.UUID, Decimal]:
    amount: dict[uuid.UUID, Decimal] = defaultdict(Decimal)
    qty: dict[uuid.UUID, Decimal] = defaultdict(Decimal)
    for t in view.between(start, end):
        if t.kind == kind and t.product_id and t.quantity and t.quantity > 0:
            amount[t.product_id] += t.amount_minor
            qty[t.product_id] += t.quantity
    return {pid: amount[pid] / qty[pid] for pid in amount}


def _qty(view: LedgerView, kind: K, start: date, end: date) -> dict[uuid.UUID, Decimal]:
    out: dict[uuid.UUID, Decimal] = defaultdict(Decimal)
    for t in view.between(start, end):
        if t.kind == kind and t.product_id and t.quantity:
            out[t.product_id] += t.quantity
    return out


def input_cost_changes(view: LedgerView, start: date, end: date) -> list[PriceChange]:
    """Per-product purchase unit cost this period vs. last (PRD §13.3 groundwork)."""
    ps, pe = previous_period(start, end)
    cost_now = _unit_prices(view, K.PURCHASE, start, end)
    cost_before = _unit_prices(view, K.PURCHASE, ps, pe)
    price_now = _unit_prices(view, K.SALE, start, end)
    price_before = _unit_prices(view, K.SALE, ps, pe)
    qty_now = _qty(view, K.PURCHASE, start, end)
    out = []
    for pid in cost_now.keys() & cost_before.keys():
        product = view.products.get(pid)
        price_chg = (
            change(price_now[pid], price_before[pid])
            if pid in price_now and pid in price_before
            else None
        )
        out.append(
            PriceChange(
                product_id=pid,
                name=product.name if product else "Unknown",
                unit_cost_now=cost_now[pid],
                unit_cost_before=cost_before[pid],
                cost_change_pct=change(cost_now[pid], cost_before[pid]) or Decimal(0),
                qty_bought_now=qty_now[pid],
                price_change_pct=price_chg,
            )
        )
    return sorted(out, key=lambda c: c.cost_change_pct, reverse=True)


@dataclass
class Snapshot:
    """Everything the intelligence layer needs for one period, computed once."""

    view: LedgerView
    start: date
    end: date
    overview: dict
    products: dict
    expenses: dict
    inventory: dict
    customers: dict
    input_costs: list[PriceChange]
    period_flows: dict[str, Decimal]
    unresolved_import_rows: int


def build_snapshot(view: LedgerView, start: date, end: date) -> Snapshot:
    flows: dict[str, Decimal] = defaultdict(Decimal)
    for t in view.between(start, end):
        if t.kind == K.SALE and t.settlement == Settlement.CREDIT:
            flows["credit_sales"] += t.amount_minor
        elif t.kind == K.CUSTOMER_PAYMENT:
            flows["customer_payments"] += t.amount_minor
        elif t.kind == K.PURCHASE:
            flows["purchases"] += t.amount_minor
    unresolved = view.db.scalar(
        select(func.count())
        .select_from(ImportRow)
        .where(
            ImportRow.business_id == view.business_id,
            ImportRow.status == ImportRowStatus.UNRESOLVED,
        )
    )
    return Snapshot(
        view=view,
        start=start,
        end=end,
        overview=overview_from(view, start, end),
        products=product_performance_from(view, start, end),
        expenses=expense_breakdown_from(view, start, end),
        inventory=inventory_from(view, as_of=end),
        customers=customers_from(view, start, end),
        input_costs=input_cost_changes(view, start, end),
        period_flows=dict(flows),
        unresolved_import_rows=unresolved or 0,
    )


