@dataclass
class Insight:
    code: str
    severity: Severity
    title: str
    what_happened: str
    why: str | None = None
    evidence: dict[str, Any] = field(default_factory=dict)
    recommendation: str | None = None
    potential_impact: str | None = None
    confidence: Level = "high"

    def as_dict(self) -> dict:
        return asdict(self)


def _revenue(s: Snapshot) -> list[Insight]:
    o = s.overview
    chg = _d(o["change_vs_previous_pct"]["revenue"])
    if chg is None:
        return []
    now, before = o["revenue"]["value"], o["previous"]["revenue"]
    if chg <= REVENUE_DROP_PCT:
        # Why: which products lost the most revenue?
        rows = s.products["products"] + s.products["stopped_selling"]
        declines = sorted(
            (
                (Decimal(r["revenue"]) - Decimal(r["previous_revenue"]), r)
                for r in rows
                if Decimal(r["revenue"]) < Decimal(r["previous_revenue"])
            ),
            key=lambda x: x[0],
        )
        total_drop = Decimal(now) - Decimal(before)
        why = None
        evidence: dict[str, Any] = {"revenue": now, "previous_revenue": before, "change_pct": chg}
        if declines and total_drop < 0:
            delta, top = declines[0]
            share = pct(delta, total_drop)
            why = (
                f"{top['name']} sales fell from ₦{Decimal(top['previous_revenue']):,.0f} to "
                f"₦{Decimal(top['revenue']):,.0f}"
                + (f", about {share}% of the total drop." if share else ".")
            )
            evidence["biggest_decline"] = {
                "product": top["name"],
                "revenue": top["revenue"],
                "previous_revenue": top["previous_revenue"],
            }
        return [
            Insight(
                code="revenue_down",
                severity="critical" if chg <= REVENUE_DROP_CRITICAL_PCT else "warning",
                title=f"Sales dropped {abs(chg)}%",
                what_happened=(
                    f"Sales were ₦{Decimal(now):,.0f}, down {abs(chg)}% from "
                    f"₦{Decimal(before):,.0f} in the previous period."
                ),
                why=why,
                evidence=evidence,
                recommendation=(
                    f"Look at what changed for {evidence['biggest_decline']['product']}: price, "
                    "availability, or customer demand."
                    if "biggest_decline" in evidence
                    else "Check whether all sales were recorded, then look for changes in "
                    "demand, pricing or stock availability."
                ),
                confidence=o["confidence"]["level"],
            )
        ]
    if chg >= REVENUE_GROWTH_PCT:
        return [
            Insight(
                code="revenue_up",
                severity="positive",
                title=f"Sales grew {chg}%",
                what_happened=(
                    f"Sales were ₦{Decimal(now):,.0f}, up {chg}% from ₦{Decimal(before):,.0f}."
                ),
                evidence={"revenue": now, "previous_revenue": before, "change_pct": chg},
                confidence=o["confidence"]["level"],
            )
        ]
    return []


def _input_costs(s: Snapshot) -> list[Insight]:
    out = []
    for c in s.input_costs:
        if c.cost_change_pct < INPUT_COST_RISE_PCT:
            continue
        extra = (c.unit_cost_now - c.unit_cost_before) * c.qty_bought_now
        squeeze = c.price_change_pct is not None and c.price_change_pct < c.cost_change_pct
        why = None
        if c.price_change_pct is not None:
            why = (
                f"Your selling price for {c.name} changed {c.price_change_pct}% while its "
                f"cost rose {c.cost_change_pct}%"
                + (", so each sale earns less." if squeeze else ".")
            )
        out.append(
            Insight(
                code="input_cost_up",
                severity="warning",
                title=f"{c.name} is costing you {c.cost_change_pct}% more",
                what_happened=(
                    f"The average cost of {c.name} rose from {naira(c.unit_cost_before)} to "
                    f"{naira(c.unit_cost_now)} per unit."
                ),
                why=why,
                evidence={
                    "product": c.name,
                    "unit_cost_now": str(money(c.unit_cost_now)),
                    "unit_cost_before": str(money(c.unit_cost_before)),
                    "cost_change_pct": c.cost_change_pct,
                    "selling_price_change_pct": c.price_change_pct,
                },
                recommendation=(
                    f"Compare prices from other {c.name} suppliers before your next purchase"
                    + (
                        ", and consider a selling-price adjustment if the market allows."
                        if squeeze
                        else "."
                    )
                ),
                potential_impact=(
                    f"About {naira(extra)} extra spent on {c.name} this period."
                    if extra > 0
                    else None
                ),
            )
        )
    return out[:3]


def _margin(s: Snapshot) -> list[Insight]:
    o = s.overview
    now, before = _d(o["gross_margin_pct"]), _d(o["previous"]["gross_margin_pct"])
    if now is None or before is None:
        return []
    if (
        o["gross_profit"]["basis"] != "calculated"
        or o["previous"]["gross_margin_basis"] != "calculated"
    ):
        return []  # don't alarm on estimated margins
    if before - now < MARGIN_DROP_POINTS:
        return []
    rising = [c for c in s.input_costs if c.cost_change_pct >= INPUT_COST_RISE_PCT]
    return [
        Insight(
            code="margin_down",
            severity="warning",
            title=f"Gross margin fell from {before}% to {now}%",
            what_happened=(
                f"You kept {now} kobo of every naira of sales after product costs, down from "
                f"{before}."
            ),
            why=(
                "Product costs rose faster than selling prices: "
                + ", ".join(f"{c.name} +{c.cost_change_pct}%" for c in rising[:3])
                + "."
                if rising
                else "Product mix shifted toward lower-margin items, or selling prices fell."
            ),
            evidence={"gross_margin_pct": now, "previous_gross_margin_pct": before},
            recommendation="Review prices on your lowest-margin products.",
        )
    ]


def _expenses(s: Snapshot) -> list[Insight]:
    out = []
    o = s.overview
    rev_chg = _d(o["change_vs_previous_pct"]["revenue"])
    opex_chg = _d(o["change_vs_previous_pct"]["operating_expenses"])
    if (
        opex_chg is not None
        and rev_chg is not None
        and opex_chg > 0
        and opex_chg - rev_chg >= EXPENSES_OUTPACE_POINTS
    ):
        out.append(
            Insight(
                code="expenses_outpacing_revenue",
                severity="warning",
                title="Expenses are growing faster than sales",
                what_happened=(
                    f"Operating expenses changed {opex_chg}% while sales changed {rev_chg}%."
                ),
                evidence={"expenses_change_pct": opex_chg, "revenue_change_pct": rev_chg},
                recommendation="Check which expenses grew and whether they brought more sales.",
            )
        )
    for cat in s.expenses["categories"]:
        chg, share = _d(cat["change_pct"]), _d(cat["share_pct"])
        if chg is None or share is None:
            continue
        if chg >= EXPENSE_CATEGORY_RISE_PCT and share >= EXPENSE_CATEGORY_MIN_SHARE_PCT:
            label = cat["category"].replace("_", " ")
            extra = Decimal(cat["amount"]) - Decimal(cat["previous_amount"])
            out.append(
                Insight(
                    code="expense_category_up",
                    severity="warning",
                    title=f"{label.capitalize()} costs rose {chg}%",
                    what_happened=(
                        f"You spent ₦{Decimal(cat['amount']):,.0f} on {label}, up from "
                        f"₦{Decimal(cat['previous_amount']):,.0f}."
                    ),
                    evidence={
                        "category": cat["category"],
                        "amount": cat["amount"],
                        "previous_amount": cat["previous_amount"],
                        "change_pct": chg,
                        "share_of_expenses_pct": share,
                    },
                    recommendation=f"Check whether the extra {label} spending was necessary.",
                    potential_impact=f"₦{extra:,.0f} more than the previous period.",
                )
            )
    return out


def _profit_and_cash(s: Snapshot) -> list[Insight]:
    o = s.overview
    out = []
    net = Decimal(o["net_profit"]["value"])
    estimated = o["net_profit"]["basis"] == "estimated"
    withdrawn = Decimal(o["personal_expenses"]["value"]) + Decimal(o["owner_withdrawals"]["value"])
    cash_flow = Decimal(o["net_cash_flow"]["value"])
    conf = o["confidence"]["level"]

    if net < 0 and Decimal(o["revenue"]["value"]) > 0:
        out.append(
            Insight(
                code="net_loss",
                severity="warning" if estimated else "critical",
                title="The business made a loss",
                what_happened=(
                    f"{'Estimated' if estimated else 'Net'} result for the period: "
                    f"-₦{abs(net):,.0f}."
                ),
                evidence={
                    "net_profit": str(net),
                    "basis": o["net_profit"]["basis"],
                    "revenue": o["revenue"]["value"],
                    "operating_expenses": o["operating_expenses"]["value"],
                },
                recommendation="Review your largest expenses and your product margins.",
                confidence=conf,
            )
        )

    # PRD §12: profit vs money taken out for personal use.
    if withdrawn > 0 and net > 0:
        retained = net - withdrawn
        if withdrawn > net:
            out.append(
                Insight(
                    code="withdrawals_exceed_profit",
                    severity="warning",
                    title="More money left the business than it earned",
                    what_happened=(
                        f"The business made about ₦{net:,.0f} profit, but ₦{withdrawn:,.0f} was "
                        "taken out for personal use."
                    ),
                    why="Personal spending and withdrawals were larger than profit, so the "
                    "difference came out of business cash or stock.",
                    evidence={"net_profit": str(net), "withdrawn": str(withdrawn)},
                    recommendation="Set a fixed monthly amount to pay yourself, below your "
                    "typical profit.",
                    potential_impact=f"Business cash reduced by about ₦{abs(retained):,.0f}.",
                    confidence=conf,
                )
            )
        elif withdrawn >= net * Decimal("0.7"):
            out.append(
                Insight(
                    code="high_withdrawals",
                    severity="info",
                    title="Most of the profit was withdrawn",
                    what_happened=(
                        f"The business made about ₦{net:,.0f} profit; ₦{withdrawn:,.0f} was taken "
                        f"out, leaving about ₦{retained:,.0f} in the business."
                    ),
                    evidence={"net_profit": str(net), "withdrawn": str(withdrawn)},
                    recommendation="Keeping more profit in the business helps it grow and "
                    "handle slow months.",
                    confidence=conf,
                )
            )

    # "Why is my cash low when sales are high?"
    if cash_flow < 0 and net > 0:
        flows = s.period_flows
        reasons: dict[str, Decimal] = {}
        new_credit = money(flows.get("credit_sales", 0) - flows.get("customer_payments", 0))
        if new_credit > 0:
            reasons["unpaid customer sales"] = new_credit
        stock_build = money(flows.get("purchases", 0)) - Decimal(o["cost_of_goods_sold"]["value"])
        if stock_build > 0:
            reasons["stock bought but not yet sold"] = stock_build
        if withdrawn > 0:
            reasons["personal spending and withdrawals"] = withdrawn
        top = sorted(reasons.items(), key=lambda kv: kv[1], reverse=True)
        out.append(
            Insight(
                code="cash_squeeze",
                severity="warning",
                title="Profit is positive but cash went down",
                what_happened=(
                    f"The business made about ₦{net:,.0f} profit, yet cash fell by "
                    f"₦{abs(cash_flow):,.0f}."
                ),
                why=(
                    "Cash is tied up in " + "; ".join(f"{k} (₦{v:,.0f})" for k, v in top) + "."
                    if top
                    else None
                ),
                evidence={k: str(v) for k, v in reasons.items()}
                | {"net_profit": str(net), "net_cash_flow": str(cash_flow)},
                recommendation=(
                    "Collect what customers owe you"
                    if new_credit > 0
                    else "Buy stock closer to when you need it"
                )
                + ", and watch cash as closely as profit.",
                confidence=conf,
            )
        )

    receivables = Decimal(o["receivables"]["value"])
    revenue = Decimal(o["revenue"]["value"])
    if receivables > 0 and revenue > 0 and pct(receivables, revenue) >= RECEIVABLES_SHARE_PCT:
        debtors = s.customers["customers_owing"][:3]
        out.append(
            Insight(
                code="high_receivables",
                severity="warning",
                title=f"Customers owe you ₦{receivables:,.0f}",
                what_happened=(
                    f"Unpaid customer sales equal {pct(receivables, revenue)}% of this "
                    "period's sales."
                ),
                evidence={
                    "receivables": str(receivables),
                    "largest_debtors": [{"name": d["name"], "owing": d["owing"]} for d in debtors],
                },
                recommendation=(
                    "Follow up with "
                    + ", ".join(f"{d['name']} (₦{Decimal(d['owing']):,.0f})" for d in debtors)
                    + "."
                    if debtors
                    else "Follow up on unpaid sales."
                ),
            )
        )
    return out


def _stock(s: Snapshot) -> list[Insight]:
    out = []
    items = s.inventory["_items"]
    for i in [i for i in items if i.status in ("low", "out_of_stock") and i.movement != "slow"][:3]:
        unit = f" {i.unit}" if i.unit else ""
        days = f"about {i.days_left.quantize(Decimal('1'))} days" if i.days_left else "no"
        out.append(
            Insight(
                code="low_stock",
                severity="warning",
                title=(
                    f"{i.name} is out of stock"
                    if i.status == "out_of_stock"
                    else f"{i.name} may run out in {days}"
                ),
                what_happened=(
                    f"Estimated {i.on_hand}{unit} left, selling about "
                    f"{i.daily_rate.quantize(Decimal('0.1'))}{unit} a day."
                ),
                evidence=i.as_dict(),
                recommendation=(
                    f"Reorder about {i.reorder_qty}{unit}"
                    + (f" (≈{naira(i.reorder_cost_minor)})" if i.reorder_cost_minor else "")
                    + " to cover two weeks."
                    if i.reorder_qty
                    else "Reorder soon."
                ),
                potential_impact=(
                    f"Running out could cost about {naira(i.revenue_in_window / 30 * 7)} in "
                    "sales per week."
                    if i.revenue_in_window
                    else None
                ),
                confidence="medium",  # stock is estimated, not counted
            )
        )
    dead = [i for i in items if i.status == "dead"]
    if dead:
        value = sum((i.value_minor for i in dead), Decimal(0))
        out.append(
            Insight(
                code="dead_stock",
                severity="info",
                title=f"{naira(value)} is sitting in stock that isn't selling",
                what_happened=(
                    "No sales in 60+ days for: " + ", ".join(i.name for i in dead[:5]) + "."
                ),
                evidence={"products": [i.name for i in dead], "value": str(money(value))},
                recommendation="Consider discounting or bundling these items to free up cash, "
                "and avoid restocking them for now.",
                confidence="medium",
            )
        )
    return out


def _stock_counts(s: Snapshot) -> list[Insight]:
    """What physical counts revealed: missing stock (shrinkage) and unexplained surplus."""
    out = []
    adjustments = s.view.adjustments_between(s.start, s.end)

    def name(pid: uuid.UUID) -> str:
        product = s.view.products.get(pid)
        return product.name if product else "Unknown"

    losses = [a for a in adjustments if a.variance_qty < 0]
    if losses:
        valued = [a for a in losses if a.value_minor is not None]
        total = -sum((a.value_minor for a in valued), Decimal(0))
        worst = sorted(valued, key=lambda a: a.value_minor)[:5]
        revenue = Decimal(s.overview["revenue"]["value"])
        share = pct(money(total), revenue) if revenue else None
        out.append(
            Insight(
                code="stock_loss",
                severity="warning",
                title=(
                    f"{naira(total)} of stock is unaccounted for"
                    if total
                    else "Stock counts found missing items"
                ),
                what_happened=(
                    "Your stock count found less than your records show for "
                    + ", ".join(
                        f"{name(a.count.product_id)} ({abs(a.variance_qty.normalize())} missing)"
                        for a in (worst or losses[:5])
                    )
                    + "."
                ),
                why="Common causes are unrecorded sales, spoilage or damage, items given out "
                "on credit without a record, or theft.",
                evidence={
                    "missing_value": str(money(total)),
                    "share_of_sales_pct": share,
                    "items": [
                        {
                            "product": name(a.count.product_id),
                            "counted_on": a.count.counted_on,
                            "expected": str(a.expected_qty),
                            "counted": str(a.count.counted_qty),
                            "value": str(money(-a.value_minor)) if a.value_minor else None,
                        }
                        for a in losses
                    ],
                },
                recommendation="Check that every sale is being recorded, and count these "
                "items more often to see when the losses happen.",
                potential_impact=(
                    f"This reduced your profit by {naira(total)}."
                    if total and s.overview["cost_of_goods_sold"]["method"] != "purchases_in_period"
                    else None
                ),
            )
        )
    surplus = [a for a in adjustments if a.variance_qty > 0]
    if surplus:
        out.append(
            Insight(
                code="stock_surplus",
                severity="info",
                title="Some stock counts found more than your records",
                what_happened=(
                    "You have more on the shelf than recorded for "
                    + ", ".join(name(a.count.product_id) for a in surplus[:5])
                    + "."
                ),
                why="This usually means a purchase wasn't recorded.",
                recommendation="Add any missing purchases so your costs and profit are right.",
            )
        )
    return out


def _customers(s: Snapshot) -> list[Insight]:
    out = []
    c = s.customers
    conf = c["confidence"]["level"]
    if conf == "low":
        return []
    top_share = _d(c["summary"]["top_customer_share_pct"])
    if top_share and top_share >= CONCENTRATION_PCT and c["summary"]["active_customers"] > 1:
        top = c["top_customers"][0]
        out.append(
            Insight(
                code="customer_concentration",
                severity="info",
                title=f"{top['name']} brings {top_share}% of your sales",
                what_happened="A large share of your sales depends on one customer.",
                evidence={"customer": top["name"], "share_pct": top_share},
                recommendation="Keep this customer happy, and work on growing other customers "
                "so a change on their side doesn't hit you hard.",
                confidence=conf,
            )
        )
    dormant = c["dormant_customers"]
    if dormant:
        names = ", ".join(d["name"] for d in dormant[:3])
        out.append(
            Insight(
                code="dormant_customers",
                severity="info",
                title=f"{len(dormant)} regular customer(s) have stopped buying",
                what_happened=f"{names} haven't bought in longer than usual.",
                evidence={"customers": dormant[:5]},
                recommendation="Reach out to them: a call or message can bring them back.",
                confidence=conf,
            )
        )
    return out


def _data_quality(s: Snapshot) -> list[Insight]:
    out = []
    d = s.overview["data"]
    if d["provisional_excluded"]:
        out.append(
            Insight(
                code="unconfirmed_transactions",
                severity="info",
                title=f"Confirm {d['provisional_excluded']} transaction(s)",
                what_happened=(
                    f"₦{Decimal(d['provisional_amount']):,.0f} of transactions are waiting for "
                    "your confirmation and are left out of your numbers."
                ),
                recommendation="Review and confirm them to make your reports complete.",
            )
        )
    if s.unresolved_import_rows:
        out.append(
            Insight(
                code="unresolved_records",
                severity="info",
                title=f"{s.unresolved_import_rows} imported record(s) need attention",
                what_happened="Some rows from your uploads couldn't be read reliably and were "
                "not added.",
                recommendation="Re-upload them with the missing details or enter them manually.",
            )
        )
    coverage = _d(d["cost_coverage_pct"])
    revenue = Decimal(s.overview["revenue"]["value"])
    if revenue > 0 and coverage is not None and coverage < 95:
        out.append(
            Insight(
                code="profit_is_estimated",
                severity="info",
                title="Your profit is an estimate",
                what_happened=(
                    f"Only {coverage}% of sales can be matched to what the items cost you."
                ),
                recommendation="Record product names and quantities on purchases and sales to "
                "get exact profit per product.",
            )
        )
    return out


